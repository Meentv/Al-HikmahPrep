ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / 'site/index.html'


def state(p):
    return p.evaluate('(key) => JSON.parse(localStorage.getItem(key))', KEY)


def goto(p, fragment, selector=None):
    p.goto(BASE + '#' + fragment)
    if selector:
        expect(p.locator(selector).first).to_be_visible(timeout=3500)


def finish(p, action):
    p.get_by_role('button', name=action, exact=True).click()
    p.get_by_role('button', name='Submit & see score').click()
    expect(p.locator('.result-hero')).to_be_visible()


def answer(p, index):
    p.locator('#option-list input').nth(index).check()


def legacy(browser, old_key, record, route, expected):
    p = browser.new_page(reduced_motion='reduce')
    p.goto(BASE)
    p.evaluate('([k,v]) => localStorage.setItem(k,JSON.stringify(v))', [old_key, record])
    goto(p, route)
    p.reload()
    expect(p.locator('.activity-list,.question-panel').first).to_contain_text(expected, timeout=3500)
    return p


