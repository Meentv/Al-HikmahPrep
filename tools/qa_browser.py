def motion(browser):
    p=browser.new_page(reduced_motion='no-preference')
    p.goto(BASE)
    p.evaluate('''() => { if(document.startViewTransition){const actual=document.startViewTransition.bind(document);document.startViewTransition=(...args)=>{window.motionCalls=(window.motionCalls||0)+1;return actual(...args);};} }''')
    p.locator('.desk-hero').hover(position={'x':40,'y':90})
    expect(p.locator('.desk-hero')).to_have_class(re.compile('pointer-active'))
    assert p.locator('.desk-hero').evaluate("el=>el.style.getPropertyValue('--drift-x')").startswith('-')
    p.mouse.move(20,20)
    expect(p.locator('.desk-hero')).not_to_have_class(re.compile('pointer-active'))
    p.locator('.activity-zone').scroll_into_view_if_needed()
    expect(p.locator('.activity-zone')).to_have_class(re.compile('revealed'))
    p.locator('.rail-link[data-nav=courses]').click()
    expect(p.locator('h1')).to_have_text('My courses')
    if p.evaluate('!!document.startViewTransition'):
        assert p.evaluate('window.motionCalls') >= 1
    p.locator('.rail-link[data-nav=flashcards]').click()
    expect(p.locator('.flash-flip')).to_be_visible()
    p.get_by_role('button',name='Reveal answer').click()
    expect(p.locator('.flash-flip')).to_have_class(re.compile('flipped'))
    p.emulate_media(reduced_motion='reduce')
    p.locator('.rail-link[data-nav=dashboard]').click()
    expect(p.locator('h1')).to_contain_text('Welcome back')
    assert p.evaluate('getComputedStyle(document.querySelector("#view")).animationName === "none"')
    p.locator('.desk-hero').hover()
    expect(p.locator('.desk-hero')).not_to_have_class(re.compile('pointer-active'))
    p.locator('.activity-zone').scroll_into_view_if_needed()
    expect(p.locator('.activity-zone')).not_to_have_class(re.compile('revealed'))
    p.close()
    fallback=browser.new_page()
    fallback.add_init_script('window.IntersectionObserver=undefined;document.startViewTransition=undefined;')
    fallback.goto(BASE)
    expect(fallback.locator('.activity-zone')).to_be_visible()
    fallback.locator('.rail-link[data-nav=courses]').click()
    expect(fallback.locator('h1')).to_have_text('My courses')
    fallback.close()
    print('Mouse-only hero movement, one-time scroll reveal, route and flip transitions, reduced motion and missing-API fallback: pass')


